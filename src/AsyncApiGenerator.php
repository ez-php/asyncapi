<?php

declare(strict_types=1);

namespace EzPhp\AsyncApi;

use EzPhp\AsyncApi\Attributes\Channel;
use EzPhp\AsyncApi\Attributes\Message;
use EzPhp\JsonSchema\SchemaGenerator;
use ReflectionClass;

/**
 * Class AsyncApiGenerator
 *
 * Builds an AsyncAPI 3.0 document from an explicit list of message classes,
 * each annotated with #[Channel] and #[Message]:
 *
 *   - channels:   one per distinct address; `{param}` placeholders become parameters
 *   - operations: one per message class — `send<ShortName>` / `receive<ShortName>`
 *   - components: one message per class (keyed by short class name) whose payload
 *                 `$ref`s the class's JSON Schema, generated by ez-php/json-schema
 *                 into components.schemas (classes on reference cycles included)
 *
 * There is no discovery: classes not listed are not documented. A listed class
 * that cannot be documented throws, so a misconfiguration is visible instead
 * of silently producing an incomplete document.
 *
 * @package EzPhp\AsyncApi
 */
final readonly class AsyncApiGenerator
{
    /**
     * @param list<string>                        $classes Message classes to document.
     * @param string                              $title
     * @param string                              $version
     * @param array<string, array<string, mixed>> $servers AsyncAPI Server Objects keyed by name (passed through).
     */
    public function __construct(
        private array $classes,
        private string $title = 'API',
        private string $version = '1.0.0',
        private array $servers = [],
    ) {
    }

    /**
     * @throws AsyncApiException When a listed class cannot be documented.
     *
     * @return AsyncApiDocument
     */
    public function generate(): AsyncApiDocument
    {
        $schemas = new SchemaGenerator('#/components/schemas/');
        $channels = [];
        $operations = [];
        $messages = [];
        $schemaDefinitions = [];

        foreach ($this->classes as $class) {
            [$channel, $message, $reflection] = $this->attributes($class);
            $name = $reflection->getShortName();

            if (isset($messages[$name])) {
                throw new AsyncApiException(sprintf('Two message classes share the short name "%s"; component keys must be unique.', $name));
            }

            $channelId = $this->channelId($channel->address);
            $channels[$channelId] ??= ['address' => $channel->address, 'messages' => []] + $this->parameters($channel->address);

            if ($channel->description !== null && !isset($channels[$channelId]['description'])) {
                $channels[$channelId]['description'] = $channel->description;
            }

            $channels[$channelId]['messages'][$name] = ['$ref' => '#/components/messages/' . $name];

            $operations[$message->action . $name] = array_filter([
                'action' => $message->action,
                'channel' => ['$ref' => '#/channels/' . $channelId],
                'messages' => [['$ref' => '#/channels/' . $channelId . '/messages/' . $name]],
                'summary' => $message->summary,
            ], static fn (mixed $value): bool => $value !== null);

            $messages[$name] = array_filter([
                'name' => $message->name,
                'summary' => $message->summary,
                'description' => $message->description,
                'contentType' => 'application/json',
                'payload' => ['$ref' => '#/components/schemas/' . $name],
            ], static fn (mixed $value): bool => $value !== null);

            foreach ($schemas->generateDefinitions($reflection->getName()) as $definition => $schema) {
                $schemaDefinitions[$definition] ??= $schema;
            }
        }

        return new AsyncApiDocument(
            $this->title,
            $this->version,
            $this->servers,
            $channels,
            $operations,
            ['messages' => $messages, 'schemas' => $schemaDefinitions],
        );
    }

    /**
     * @throws AsyncApiException
     *
     * @return array{Channel, Message, ReflectionClass<object>}
     */
    private function attributes(string $class): array
    {
        if (!class_exists($class)) {
            throw new AsyncApiException(sprintf('Message class "%s" does not exist.', $class));
        }

        $reflection = new ReflectionClass($class);
        $channel = ($reflection->getAttributes(Channel::class)[0] ?? null)?->newInstance();
        $message = ($reflection->getAttributes(Message::class)[0] ?? null)?->newInstance();

        if ($channel === null || $message === null) {
            throw new AsyncApiException(sprintf('Message class "%s" needs both #[Channel] and #[Message].', $class));
        }

        if (!in_array($message->action, [Message::SEND, Message::RECEIVE], true)) {
            throw new AsyncApiException(sprintf('Message class "%s": action must be "send" or "receive", got "%s".', $class, $message->action));
        }

        return [$channel, $message, $reflection];
    }

    /**
     * A component-safe channel id: placeholders unwrapped, everything outside
     * [A-Za-z0-9_-] replaced by "_" — "orders.{orderId}" → "orders_orderId".
     */
    private function channelId(string $address): string
    {
        $id = trim((string) preg_replace('/[^A-Za-z0-9_\-]+/', '_', str_replace(['{', '}'], '', $address)), '_');

        return $id !== '' ? $id : 'root';
    }

    /**
     * @return array{parameters?: array<string, array<string, never>>}
     */
    private function parameters(string $address): array
    {
        preg_match_all('/\{([^}]+)\}/', $address, $matches);

        if ($matches[1] === []) {
            return [];
        }

        return ['parameters' => array_fill_keys($matches[1], [])];
    }
}
